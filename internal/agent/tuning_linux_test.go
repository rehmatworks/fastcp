func TestDesiredPoolsReloadGracefully(t *testing.T) {
	installed := map[string]bool{"8.3": true, "8.4": true}
	pools := desiredPools(buildPlan(testState(), testLookup, installed, "8.4"), 4096, "8.4", installed)
	global, ok := pools["/etc/php/8.3/fpm/pool.d/fastcp-global.conf"]
	if !ok || global.Version != "8.3" || global.Content != fpmGlobalConf || global.Socket != "" {
		t.Fatalf("PHP 8.3 global settings = %+v (present %v)", global, ok)
	}
	if !strings.Contains(global.Content, "[global]\nprocess_control_timeout = 10s\n") {
		t.Errorf("global settings do not let a reload wait for requests:\n%s", global.Content)
	}
	if _, ok := pools["/etc/php/8.4/fpm/pool.d/fastcp-global.conf"]; ok {
		t.Error("global settings written for PHP 8.4, which runs no FastCP pools")
	}
}

func TestRenderMySQLConfigTableCaches(t *testing.T) {
	out := renderMySQLConfig(defaultMySQLConfig(16384))
	for _, want := range []string{"table_open_cache = 4000\n", "table_definition_cache = 2000\n", "innodb_buffer_pool_size = 1024M\n"} {
		if !strings.Contains(out, want) {
			t.Errorf("MySQL tuning missing %q:\n%s", want, out)
		}
	}
	if !strings.HasPrefix(out, "# Generated by FastCP.") {
		t.Errorf("MySQL tuning lost the header that marks it as FastCP's:\n%s", out)
	}
}
