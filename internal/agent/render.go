type renderOptions struct {
	// Dev serves plain HTTP without certificates (local Docker / macOS).
	Dev bool
	// PMASocket is the phpMyAdmin FPM socket; empty disables the PMA site.
	PMASocket string
	// Admin is the Caddy admin endpoint.
	Admin string
	// OwnerFS is set when FastCP's Caddy build is installed. Each site is
	// then served through its fastcp_owner file system, which refuses links
	// to files of other users, and may use its fastcp_page_cache handler.
	OwnerFS bool
	// Custom lists the administrator's own configuration, as last applied.
	Custom []customFile
}

// ownerFSName names the fastcp_owner file system of a user.
func ownerFSName(username string) string { return "fastcp_" + username }

func caddyQuote(s string) string { return strconv.Quote(s) }

// cloudflareFlexibleMessage is a single line: Caddyfile strings keep
// escape sequences such as \n literally.
const cloudflareFlexibleMessage = "This site is behind Cloudflare with SSL/TLS encryption set to Flexible: " +
	"Cloudflare connects to this server over plain HTTP, and the server redirects every HTTP request to HTTPS, so the page would never load. " +
	"To fix it, open the domain in Cloudflare, go to SSL/TLS, and set the encryption mode to Full (strict)."

// renderCaddyfile produces the complete Caddyfile. All values come from a
// validated plan, so domains, paths and header values contain no Caddyfile
// syntax or placeholders.
func renderCaddyfile(p *plan, cfg CaddyConfig, opt renderOptions) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	sites := append([]*sitePlan(nil), p.Sites...)
	sort.Slice(sites, func(i, j int) bool {
		if sites[i].Username != sites[j].Username {
			return sites[i].Username < sites[j].Username
		}
		return sites[i].Slug < sites[j].Slug
	})

	w("# Generated by FastCP. Manual changes are overwritten.\n")
	w("# Put your own configuration in %s instead; see the README there.\n\n{\n", CaddyCustomDir)
	w("\tadmin %s\n", opt.Admin)
	w("\tpersist_config off\n")
	w("\tstorage file_system %s\n", CaddyStorageDir)
	if opt.OwnerFS {
		seen := map[string]bool{}
		for _, s := range sites {
			if !s.Suspended && s.ProxyURL == "" && !seen[s.Username] {
				seen[s.Username] = true
				w("\tfilesystem %s fastcp_owner %d\n", ownerFSName(s.Username), s.Tenant.UID)
			}
		}
	}
	w("\tgrace_period %s\n", cfg.GracePeriod)
	if opt.Dev {
		w("\tauto_https off\n")
	}
	w("\tlog {\n\t\tlevel ERROR\n\t}\n")
	w("\tservers {\n\t\ttimeouts {\n")
	w("\t\t\tread_header %s\n\t\t\tread_body %s\n\t\t\twrite %s\n\t\t\tidle %s\n", cfg.ReadHeader, cfg.ReadBody, cfg.WriteTimeout, cfg.IdleTimeout)
	w("\t\t}\n\t\tmax_header_size %d\n\t}\n}\n\n", cfg.MaxHeaderSize)

	w("(fastcp_hidden) {\n")
	w("\t@fastcp_hidden {\n\t\tpath */.* *.sql *.sql.gz\n\t\tnot path /.well-known/*\n\t}\n")
	w("\trespond @fastcp_hidden 404\n}\n\n")

	for _, f := range opt.Custom {
		if f.Site == "" {
			w("import %s\n\n", f.copyPath())
		}
	}

	if opt.PMASocket != "" {
		w("http://127.0.0.1:%d {\n", PMAPort)
		w("\tbind 127.0.0.1\n")
		w("\troot * %s\n", PMADir)
		w("\timport fastcp_hidden\n")
		w("\tphp_fastcgi unix/%s\n", opt.PMASocket)
		w("\tfile_server\n}\n\n")
	}

	address := func(domains []string, forceHTTPS bool) string {
		var parts []string
		for _, d := range domains {
			switch {
			case opt.Dev:
				parts = append(parts, "http://"+d)
			case forceHTTPS:
				parts = append(parts, "https://"+d)
			default:
				parts = append(parts, "http://"+d, "https://"+d)
			}
		}
		return strings.Join(parts, ", ")
	}

	// httpsRedirect replaces Caddy's automatic HTTP to HTTPS redirect.
	// Cloudflare's Flexible mode fetches over HTTP what visitors requested
	// over HTTPS, so redirecting it would loop; it gets the fix instead.
	httpsRedirect := func(s *sitePlan) {
		if !s.ForceHTTPS || opt.Dev {
			return
		}
		var parts []string
		for _, d := range append(append([]string(nil), s.Serving...), s.Redirects...) {
			parts = append(parts, "http://"+d)
		}
		w("%s {\n", strings.Join(parts, ", "))
		w("\t@cloudflare_flexible header CF-Visitor *https*\n")
		w("\troute {\n")
		w("\t\trespond @cloudflare_flexible %s 403\n", caddyQuote(cloudflareFlexibleMessage))
		w("\t\tredir https://{host}{uri} 308\n\t}\n}\n\n")
	}

	for _, s := range sites {
		w("# %s/%s (%s)\n", s.Username, s.Slug, s.ID)
		if s.Suspended {
			all := append(append([]string(nil), s.Serving...), s.Redirects...)
			w("%s {\n", address(all, s.ForceHTTPS))
			w("\troot * %s\n", SuspendedDir)
			w("\theader Cache-Control \"no-store\"\n")
			w("\trewrite * /index.html\n")
			w("\tfile_server {\n\t\tstatus 503\n\t}\n}\n\n")
			httpsRedirect(s)
			continue
		}

		w("%s {\n", address(s.Serving, s.ForceHTTPS))
		if s.ProxyURL == "" {
			w("\troot * %s\n", s.DocRoot)
			if opt.OwnerFS {
				w("\tfs %s\n", ownerFSName(s.Username))
			}
		}
		if s.CompressionEnabled {
			var algos []string
			if s.ZstdEnabled {
				algos = append(algos, "zstd")
			}
			if s.GzipEnabled {
				algos = append(algos, "gzip")
			}
			if len(algos) > 0 {
				w("\tencode %s\n", strings.Join(algos, " "))
			}
		}
		if s.CacheControl != "" {
			w("\theader Cache-Control %s\n", caddyQuote(s.CacheControl))
		}
		switch {
		case strings.HasPrefix(s.ProxyURL, "https://"):
			// The upstream's certificate and virtual host are for its own
			// name, not the visitor's.
			w("\treverse_proxy %s {\n\t\theader_up Host {upstream_hostport}\n\t}\n", s.ProxyURL)
		case s.ProxyURL != "":
			w("\treverse_proxy %s\n", s.ProxyURL)
		default:
			w("\timport fastcp_hidden\n")
			if s.Socket != "" {
				if s.PageCache && opt.OwnerFS {
					w("\tfastcp_page_cache\n")
				}
				w("\tphp_fastcgi unix/%s\n", s.Socket)
			}
			w("\tfile_server\n")
		}
		for _, f := range opt.Custom {
			if f.Site == s.Username+"/"+s.Slug {
				w("\timport %s\n", f.copyPath())
			}
		}
		if cfg.AccessLogs {
			w("\tlog {\n\t\toutput file %s {\n", path.Join(s.LogDir, "access.log"))
			w("\t\t\tmode 0640\n\t\t\troll_size 50MiB\n\t\t\troll_keep 5\n\t\t}\n\t}\n")
		}
		w("}\n\n")

		if len(s.Redirects) > 0 {
			scheme := "https"
			if opt.Dev {
				scheme = "http"
			} else if !s.ForceHTTPS {
				scheme = "{scheme}"
			}
			w("%s {\n", address(s.Redirects, s.ForceHTTPS))
			w("\tredir %s://%s{uri} permanent\n}\n\n", scheme, s.Primary)
		}
		httpsRedirect(s)
	}

	w(":80 {\n\trespond \"No site is configured for this domain.\" 404\n}\n")
	return b.String()
}

type poolTuning struct {
	MaxChildren int
	IdleTimeout string
	MaxRequests int
}

func clampInt(v, lo, hi int) int {
	if v < lo {
		return lo
	}
	if v > hi {
		return hi
	}
	return v
}

// sitePoolTuning sizes an on-demand pool from server RAM and the owner's
// memory limit. Idle sites start no workers, so the owner's worker budget
// is divided by the square root of their site count rather than split
// evenly, which would leave each busy site only a worker or two.
func sitePoolTuning(ramMB, userLimitMB, userSites int) poolTuning {
	if userSites < 1 {
		userSites = 1
	}
	base := clampInt(ramMB/768, 2, 64)
	if userLimitMB > 0 {
		share := 1
		for share*share < userSites {
			share++
		}
		perSite := clampInt(clampInt(userLimitMB/96, 1, 64)/share, 1, 64)
		base = min(base, perSite)
	}
	t := poolTuning{MaxChildren: base}
	switch {
	case ramMB <= 1024:
		t.MaxChildren, t.IdleTimeout, t.MaxRequests = min(base, 2), "8s", 400
	case ramMB <= 2048:
		t.MaxChildren, t.IdleTimeout, t.MaxRequests = min(base, 3), "10s", 500
	case ramMB <= 8192:
		t.IdleTimeout, t.MaxRequests = "15s", 800
	default:
		t.IdleTimeout, t.MaxRequests = "25s", 1200
	}
	t.MaxChildren = clampInt(t.MaxChildren, 1, 64)
	return t
}

// fpmGlobalConf makes a php-fpm reload let running requests finish, for up
// to 10 seconds, instead of cutting them off. New requests wait meanwhile,
// so a longer limit would hold up every site on the version.
const fpmGlobalConf = "; Generated by FastCP. Manual changes are overwritten.\n[global]\nprocess_control_timeout = 10s\n"

func renderSitePool(s *sitePlan, t poolTuning) string {
	tmp := path.Join(s.Tenant.Home, ".tmp")
	openBasedir := strings.Join([]string{s.SiteDir, tmp, "/tmp", "/usr/share/php"}, ":")
	terminate := max(s.PHPMaxExecutionTime+30, 60)
	var b strings.Builder
	fmt.Fprintf(&b, "; Generated by FastCP for %s/%s. Manual changes are overwritten.\n", s.Username, s.Slug)
	fmt.Fprintf(&b, "[%s]\n", s.PoolName)
	fmt.Fprintf(&b, "user = %s\ngroup = %s\n", s.Username, s.Username)
	fmt.Fprintf(&b, "listen = %s\nlisten.owner = %s\nlisten.group = %s\nlisten.mode = 0660\n\n", s.Socket, s.Username, CaddyUser)
	fmt.Fprintf(&b, "pm = ondemand\npm.max_children = %d\npm.process_idle_timeout = %s\npm.max_requests = %d\n\n", t.MaxChildren, t.IdleTimeout, t.MaxRequests)
	fmt.Fprintf(&b, "chdir = /\nclear_env = yes\nenv[TMPDIR] = %s\nsecurity.limit_extensions = .php\nrequest_terminate_timeout = %ds\n\n", tmp, terminate)
	fmt.Fprintf(&b, "php_admin_value[open_basedir] = %s\n", openBasedir)
	fmt.Fprintf(&b, "php_admin_value[upload_tmp_dir] = %s\n", path.Join(tmp, "uploads"))
	fmt.Fprintf(&b, "php_admin_value[sys_temp_dir] = %s\n", tmp)
	fmt.Fprintf(&b, "php_admin_value[session.save_path] = %s\n", path.Join(tmp, "sessions"))
	fmt.Fprintf(&b, "php_admin_value[soap.wsdl_cache_dir] = %s\n", path.Join(tmp, "wsdl"))
	fmt.Fprintf(&b, "php_admin_value[memory_limit] = %s\n", s.PHPMemoryLimit)
	fmt.Fprintf(&b, "php_admin_value[post_max_size] = %s\n", s.PHPPostMaxSize)
	fmt.Fprintf(&b, "php_admin_value[upload_max_filesize] = %s\n", s.PHPUploadMaxSize)
	fmt.Fprintf(&b, "php_admin_value[max_execution_time] = %d\n", s.PHPMaxExecutionTime)
	fmt.Fprintf(&b, "php_admin_value[max_input_vars] = %d\n", s.PHPMaxInputVars)
	fmt.Fprintf(&b, "php_admin_flag[log_errors] = on\n")
	fmt.Fprintf(&b, "php_admin_value[error_log] = %s\n", path.Join(s.SiteDir, "logs", "php-error.log"))
	return b.String()
}

func pmaMaxChildren(ramMB int) int {
	switch {
	case ramMB <= 1024:
		return 2
	case ramMB <= 2048:
		return 4
	case ramMB <= 4096:
		return 6
	case ramMB <= 8192:
		return 10
	default:
		return 14
	}
}

func renderPMAPool(ramMB int) string {
	var b strings.Builder
	b.WriteString("; Generated by FastCP. Manual changes are overwritten.\n[fastcp-phpmyadmin]\n")
	fmt.Fprintf(&b, "user = %s\ngroup = %s\n", PMAUser, PMAUser)
	fmt.Fprintf(&b, "listen = %s\nlisten.owner = %s\nlisten.group = %s\nlisten.mode = 0660\n\n", pmaSocketPath(), PMAUser, CaddyUser)
	fmt.Fprintf(&b, "pm = ondemand\npm.max_children = %d\npm.process_idle_timeout = 10s\npm.max_requests = 700\n\n", pmaMaxChildren(ramMB))
	b.WriteString("chdir = /\nclear_env = yes\nsecurity.limit_extensions = .php\nrequest_terminate_timeout = 300s\n\n")
	fmt.Fprintf(&b, "php_admin_value[open_basedir] = %s:%s:/usr/share/php\n", PMADir, PMATmpDir)
	for _, k := range []string{"upload_tmp_dir", "sys_temp_dir", "session.save_path"} {
		fmt.Fprintf(&b, "php_admin_value[%s] = %s\n", k, PMATmpDir)
	}
	b.WriteString("php_admin_flag[log_errors] = on\n")
	fmt.Fprintf(&b, "php_admin_value[error_log] = %s\n", path.Join(LogDir, "phpmyadmin-error.log"))
	b.WriteString("php_admin_value[upload_max_filesize] = 256M\nphp_admin_value[post_max_size] = 256M\nphp_admin_value[memory_limit] = 512M\nphp_admin_value[max_execution_time] = 300\n")
	return b.String()
}

// renderFPMIni renders FastCP's php.ini overrides for PHP-FPM. Every site on
// a PHP version shares one OPcache, so it is sized from the server's RAM
// rather than PHP's defaults, which fit only a few WordPress sites.
func renderFPMIni(ramMB int) string {
	mem := clampInt(ramMB/16, 128, 1024)
	return fmt.Sprintf(`; Managed by FastCP. Per-site limits are set in each pool.
expose_php = Off
display_errors = Off
log_errors = On
error_reporting = 22527
opcache.memory_consumption = %d
opcache.interned_strings_buffer = %d
opcache.max_accelerated_files = %d
`, mem, clampInt(mem/16, 8, 64), clampInt(mem*64, 10000, 100000))
}

// sliceLimits renders the systemd drop-in limiting a tenant's login sessions.
func sliceLimits(username string, uid, memoryMB, cpuPercent int) string {
	mem, cpu := "infinity", ""
	if memoryMB > 0 {
		mem = strconv.Itoa(memoryMB) + "M"
	}
	if cpuPercent > 0 {
		cpu = strconv.Itoa(cpuPercent) + "%"
	}
	return fmt.Sprintf("# Generated by FastCP for %s (uid %d).\n[Slice]\nMemoryMax=%s\nCPUQuota=%s\n", username, uid, mem, cpu)
}

// renderCrontab renders a tenant crontab. Commands were validated by the
// panel; they are validated again here and % is escaped so cron passes the
// command through unchanged.
func renderCrontab(jobs []CronJob) (string, []string) {
	var b strings.Builder
	var warnings []string
	b.WriteString("# Managed by FastCP. Edit cron jobs in the control panel.\nSHELL=/bin/bash\n\n")
	for _, j := range jobs {
		if !j.Enabled {
			continue
		}
		if err := validateCronJob(&j); err != nil {
			warnings = append(warnings, fmt.Sprintf("cron job %q skipped: %v", j.Name, err))
			continue
		}
		fmt.Fprintf(&b, "# %s\n%s %s\n\n", oneLine(j.Name), j.Expression, escapeCron(j.Command))
	}
	return b.String(), warnings
}

func oneLine(s string) string {
	return strings.Map(func(r rune) rune {
		if r < 0x20 || r == 0x7f {
			return ' '
		}
		return r
	}, s)
}
